// Writes src/sql/dialects/composition.ts from Unicode's UnicodeData.txt and CompositionExclusions.txt: what Unicode's
// normalization (UAX #15) needs, for the CASEI and ACCENTI functions of the `oracle` and `sqlserver` dialects, which
// normalize themselves (Oracle's COMPOSE never composes across a mark; T-SQL has no normalization at all). Unicode
// 15.0.0, as for CASEI's folding table.
// - The primary composites: each canonical decomposition of two code points whose composite isn't excluded (listed in
//   CompositionExclusions.txt, or a non-starter decomposition: the composite or its first code point has a class).
//   Singletons decompose to one code point, so they are never pairs. Hangul is composed arithmetically, not listed.
// - The canonical combining classes other than 0.
// - The full canonical decompositions (applied recursively), Hangul syllables apart (decomposed arithmetically).
//
// Usage: node scripts/gen-composition.mjs <UnicodeData.txt> <CompositionExclusions.txt> (both of Unicode 15.0.0)
// The files come from https://www.unicode.org/Public/15.0.0/ucd/ and are not kept in the repository.
//
// Encoding, to keep the tables small: entries separated by ";". Compositions "starter,mark,composite" (hex); classes
// "start,count,class" (hex, hex, decimal) for runs of consecutive code points with the same class; decompositions
// "code,part,part…" (hex).
import { readFileSync, writeFileSync } from "node:fs";

const [data, exclusions] = process.argv.slice(2);
if (!data || !exclusions) throw new Error("Usage: node scripts/gen-composition.mjs <UnicodeData.txt> <CompositionExclusions.txt>");
const lines = readFileSync(data, "utf8").split("\n").filter((line) => line.includes(";"));
const has = (hex) => lines.some((line) => line.startsWith(`${hex};`));
if (!has("11F00") || has("2EBF0")) throw new Error("Expected UnicodeData.txt of Unicode 15.0.0");
const excludedText = readFileSync(exclusions, "utf8");
if (!excludedText.startsWith("# CompositionExclusions-15.0.0.txt")) throw new Error("Expected CompositionExclusions-15.0.0.txt");
const excluded = new Set(
  excludedText.split("\n").map((line) => line.replace(/#.*/, "").trim()).filter(Boolean).map((hex) => parseInt(hex, 16)),
);

const classOf = new Map();
const decompositions = [];
for (const line of lines) {
  const fields = line.split(";");
  const code = parseInt(fields[0], 16);
  const ccc = Number(fields[3]);
  if (ccc !== 0) classOf.set(code, ccc);
  const mapping = fields[5];
  if (mapping && !mapping.startsWith("<")) decompositions.push([code, mapping.split(" ").map((hex) => parseInt(hex, 16))]);
}

const pairs = decompositions
  .filter(([code, parts]) => parts.length === 2 && !excluded.has(code) && !classOf.has(code) && !classOf.has(parts[0]))
  .map(([code, [starter, mark]]) => [starter, mark, code])
  .sort((a, b) => a[0] - b[0] || a[1] - b[1]);

const runs = [];
for (const code of [...classOf.keys()].sort((a, b) => a - b)) {
  const last = runs[runs.length - 1];
  const ccc = classOf.get(code);
  if (last && last[0] + last[1] === code && last[2] === ccc) last[1]++;
  else runs.push([code, 1, ccc]);
}

const direct = new Map(decompositions);
const full = (code) => (direct.has(code) ? direct.get(code).flatMap(full) : [code]);
const decomposed = decompositions.map(([code]) => [code, full(code)]).sort((a, b) => a[0] - b[0]);

const hex = (n) => n.toString(16);
writeFileSync(
  new URL("../src/sql/dialects/composition.ts", import.meta.url),
  `// Generated by scripts/gen-composition.mjs from UnicodeData.txt and CompositionExclusions.txt (Unicode 15.0.0): do not
// edit. What normalization (UAX #15) needs, for the CASEI and ACCENTI functions of the oracle and sqlserver dialects.
// Unicode data © 1991-2022 Unicode, Inc., used under the Unicode License: see LICENSE-UNICODE.
// ${pairs.length} primary composites; ${classOf.size} code points with a combining class, in ${runs.length} runs;
// ${decomposed.length} canonical decompositions.

/** The primary composites, "starter,mark,composite" (hex): see scripts/gen-composition.mjs. */
export const COMPOSITIONS: string =
  "${pairs.map((p) => p.map(hex).join(",")).join(";")}";

/** The canonical combining classes other than 0, "start,count,class": see scripts/gen-composition.mjs. */
export const COMBINING_CLASSES: string =
  "${runs.map(([start, count, ccc]) => `${hex(start)},${hex(count)},${ccc}`).join(";")}";

/** The full canonical decompositions but Hangul's, "code,part,part…": see scripts/gen-composition.mjs. */
export const DECOMPOSITIONS: string =
  "${decomposed.map(([code, parts]) => [code, ...parts].map(hex).join(",")).join(";")}";
`,
);
console.log(`${pairs.length} compositions, ${classOf.size} classed code points in ${runs.length} runs, ${decomposed.length} decompositions`);
