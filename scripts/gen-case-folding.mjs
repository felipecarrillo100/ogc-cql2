// Writes src/evaluate/caseFolding.ts from Unicode's CaseFolding.txt: the full case folding (statuses C and F) that
// CASEI requires (OGC 21-065r2, /req/case-insensitive-comparison/casei-function E, Unicode 15.0.0).
//
// Usage: node scripts/gen-case-folding.mjs <path to CaseFolding-15.0.0.txt>
// The file comes from https://www.unicode.org/Public/15.0.0/ucd/CaseFolding.txt and is not kept in the repository.
//
// Encoding, to keep the table small: entries separated by ";".
// - "start,count,stride,delta" (hex): `count` code points from `start`, `stride` apart, each folding to itself + delta.
// - "code:a b c" (hex): one code point folding to the code points a b c.
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/gen-case-folding.mjs <CaseFolding-15.0.0.txt>");
const text = readFileSync(source, "utf8");
const version = /^# CaseFolding-(\d+\.\d+\.\d+)\.txt/m.exec(text)?.[1];
if (version !== "15.0.0") throw new Error(`Expected CaseFolding-15.0.0.txt, got ${version ?? "an unknown file"}`);

const mappings = [];
for (const line of text.split("\n")) {
  const m = /^([0-9A-F]+); ([CF]); ([0-9A-F ]+);/.exec(line);
  if (m) mappings.push({ code: parseInt(m[1], 16), to: m[3].trim().split(" ").map((h) => parseInt(h, 16)) });
}
mappings.sort((a, b) => a.code - b.code);

const tokens = [];
for (let i = 0; i < mappings.length; ) {
  const { code, to } = mappings[i];
  if (to.length === 1) {
    const delta = to[0] - code;
    const next = mappings[i + 1];
    const stride = next && next.to.length === 1 && next.to[0] - next.code === delta ? next.code - code : 0;
    if (stride === 1 || stride === 2) {
      let count = 1;
      while (
        mappings[i + count]?.to.length === 1 &&
        mappings[i + count].code === code + count * stride &&
        mappings[i + count].to[0] - mappings[i + count].code === delta
      ) count++;
      if (count > 1) {
        tokens.push([code, count, stride, delta].map((n) => (n < 0 ? "-" + (-n).toString(16) : n.toString(16))).join(","));
        i += count;
        continue;
      }
    }
  }
  tokens.push(`${code.toString(16)}:${to.map((n) => n.toString(16)).join(" ")}`);
  i++;
}

const out = `// Generated by scripts/gen-case-folding.mjs from CaseFolding-${version}.txt: do not edit.
// Full case folding (statuses C and F), as CASEI requires (OGC 21-065r2, /req/case-insensitive-comparison/casei-function E).
// Unicode data © 1991-2022 Unicode, Inc., used under the Unicode License: see LICENSE-UNICODE.
// ${mappings.length} code points, in ${tokens.length} entries.

/** The encoded table: see scripts/gen-case-folding.mjs. */
export const CASE_FOLDING: string =
  ${JSON.stringify(tokens.join(";"))};
`;
writeFileSync(new URL("../src/evaluate/caseFolding.ts", import.meta.url), out);
console.log(`${mappings.length} code points, ${tokens.length} entries, ${out.length} bytes`);
