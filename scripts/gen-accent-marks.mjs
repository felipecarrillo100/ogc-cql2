// Writes src/evaluate/accentMarks.ts from Unicode's UnicodeData.txt: the nonspacing marks (general category Mn) that
// ACCENTI removes after canonical decomposition (OGC 21-065r2, /req/accent-insensitive-comparison/accenti-function E
// and its implementation note), minus the Japanese voicing marks U+3099 and U+309A, which it keeps
// (/rec/accent-insensitive-comparison/japanese-non-spacing-marks). Unicode 15.0.0, as for CASEI.
//
// Usage: node scripts/gen-accent-marks.mjs <path to UnicodeData.txt of Unicode 15.0.0>
// The file comes from https://www.unicode.org/Public/15.0.0/ucd/UnicodeData.txt and is not kept in the repository.
//
// Encoding, to keep the table small: ranges separated by ";", each "start,count" (hex).
import { readFileSync, writeFileSync } from "node:fs";

const source = process.argv[2];
if (!source) throw new Error("Usage: node scripts/gen-accent-marks.mjs <UnicodeData.txt of Unicode 15.0.0>");
const lines = readFileSync(source, "utf8").split("\n");
// UnicodeData.txt carries no version line: check a code point added in 15.0.0, and that none of 15.1 is there.
const has = (hex) => lines.some((line) => line.startsWith(`${hex};`));
if (!has("11F00") || has("2EBF0")) throw new Error("Expected UnicodeData.txt of Unicode 15.0.0");

const KEEP = new Set([0x3099, 0x309a]);
const marks = [];
for (const line of lines) {
  const [hex, , category] = line.split(";");
  if (category === "Mn" && !KEEP.has(parseInt(hex, 16))) marks.push(parseInt(hex, 16));
}
marks.sort((a, b) => a - b);

const ranges = [];
for (const code of marks) {
  const last = ranges[ranges.length - 1];
  if (last && last[0] + last[1] === code) last[1]++;
  else ranges.push([code, 1]);
}
const encoded = ranges.map(([start, count]) => `${start.toString(16)},${count.toString(16)}`).join(";");

writeFileSync(
  new URL("../src/evaluate/accentMarks.ts", import.meta.url),
  `// Generated by scripts/gen-accent-marks.mjs from UnicodeData.txt (Unicode 15.0.0): do not edit.
// The nonspacing marks (category Mn) that ACCENTI removes, minus U+3099 and U+309A (OGC 21-065r2, Recommendation 2).
// Unicode data © 1991-2022 Unicode, Inc., used under the Unicode License: see LICENSE-UNICODE.
// ${marks.length} code points, in ${ranges.length} ranges.

/** The encoded table: see scripts/gen-accent-marks.mjs. */
export const ACCENT_MARKS: string =
  ${JSON.stringify(encoded)};
`,
);
console.log(`${marks.length} marks in ${ranges.length} ranges`);
